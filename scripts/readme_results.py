"""README "Results" table from T5 (owner: Supriye; S33 step 2).

Writes the main comparison table, built from results/tables/model_comparison.csv (T5, Ayo's
Y17 on the results machine), between the two markers in README.md, so the README never holds
numbers typed by hand:

    python scripts/readme_results.py           # rewrite the table in README.md
    python scripts/readme_results.py --check   # exit 1 if README.md is out of date

tests/test_readme_results.py runs the check, so a re-run of `python -m src.evaluate report` that
changes T5 fails the tests until this script is run again.
"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.config import TABLES_DIR  # noqa: E402  (needs ROOT on the path)

README = ROOT / "README.md"
T5 = TABLES_DIR / "model_comparison.csv"
START = "<!-- results:start (generated by scripts/readme_results.py from model_comparison.csv) -->"
END = "<!-- results:end -->"

MODEL_NAMES = {
    "iforest": "Isolation Forest",
    "autoencoder": "Autoencoder",
    "ocsvm": "One-Class SVM",
    "iforest_contam": "Isolation Forest, all train rows",
    "autoencoder_contam": "Autoencoder, all train rows",
    "random_forest": "Random Forest",
    "xgboost": "XGBoost",
}
POINT_NAMES = {"best_f1": "best-F1", "top_1pct": "top 1%"}
# (T5 column, README header, decimals)
COLUMNS = [
    ("precision", "Precision", 3),
    ("recall", "Recall", 3),
    ("f1", "F1", 3),
    ("fpr", "FPR", 4),
    ("fnr", "FNR", 3),
    ("roc_auc", "ROC-AUC", 3),
    ("pr_auc", "PR-AUC", 3),
    ("user_recall", "User recall", 3),
    ("median_delay_days", "Median delay (days)", 1),
]


def _cell(value, decimals) -> str:
    return "–" if pd.isna(value) else f"{float(value):.{decimals}f}"


def results_markdown(table: pd.DataFrame) -> str:
    """The README table: one row per model and operating point, in T5's row order."""
    missing = [c for c, _, _ in COLUMNS if c not in table] + \
              [c for c in ("model", "operating_point") if c not in table]
    if missing:
        raise ValueError(f"model_comparison.csv lacks columns {missing}")
    header = ["Model", "Operating point"] + [h for _, h, _ in COLUMNS]
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join(["---"] * 2 + ["---:"] * len(COLUMNS)) + "|"]
    for row in table.itertuples(index=False):
        cells = [MODEL_NAMES.get(row.model, row.model),
                 POINT_NAMES.get(row.operating_point, row.operating_point)]
        cells += [_cell(getattr(row, c), d) for c, _, d in COLUMNS]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render(readme: str, table: pd.DataFrame) -> str:
    """`readme` with the text between START and END replaced by the table (markers kept)."""
    if readme.count(START) != 1 or readme.count(END) != 1 or readme.index(START) > readme.index(END):
        raise ValueError("README.md needs exactly one results:start marker before one results:end")
    head, rest = readme.split(START)
    _, tail = rest.split(END)
    return f"{head}{START}\n{results_markdown(table)}\n{END}{tail}"


def read_readme(path=README) -> str:
    """README.md with LF line endings (a Windows checkout with core.autocrlf has CRLF)."""
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def main(argv) -> int:
    readme = read_readme()
    new = render(readme, pd.read_csv(T5))
    if argv[:1] == ["--check"]:
        if new != readme:
            print("README.md results table is out of date: run python scripts/readme_results.py")
            return 1
        print("README.md results table matches model_comparison.csv")
        return 0
    README.write_text(new, encoding="utf-8", newline="\n")
    print(f"wrote the results table ({len(pd.read_csv(T5))} rows) into README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
